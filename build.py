"""Build Modbus Studio into a portable single-file Windows executable."""

from __future__ import annotations

import argparse
import importlib.util
import os
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parent
DIST_DIR = ROOT / "dist"
BUILD_DIR = ROOT / "build"
RESOURCE_DIR = ROOT / "resources"
APP_NAME = "ModbusStudio"
VERSION = (0, 1, 0, 0)
EXCLUDED_MODULES = [
    "PyQt5", "PyQt6", "PySide2", "tkinter",
    "PySide6.Qt3DCore", "PySide6.QtCharts", "PySide6.QtDataVisualization",
    "PySide6.QtGraphs", "PySide6.QtMultimedia", "PySide6.QtNetwork",
    "PySide6.QtOpenGL", "PySide6.QtPdf", "PySide6.QtQml", "PySide6.QtQuick",
    "PySide6.QtRemoteObjects", "PySide6.QtScxml", "PySide6.QtSensors",
    "PySide6.QtSerialPort", "PySide6.QtSpatialAudio", "PySide6.QtSvg",
    "PySide6.QtVirtualKeyboard", "PySide6.QtWebChannel", "PySide6.QtWebEngineCore",
]


def _require_build_dependencies() -> None:
    missing = []
    for module, package in (("PIL", "Pillow"), ("PyInstaller", "pyinstaller")):
        if importlib.util.find_spec(module) is None:
            missing.append(package)
    if missing:
        packages = " ".join(missing)
        raise SystemExit(
            f"缺少打包依赖：{', '.join(missing)}\n"
            f"请运行：{sys.executable} -m pip install {packages}"
        )


def _write_version_file() -> Path:
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    version_file = BUILD_DIR / "windows_version_info.txt"
    version_file.write_text(
        """VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=(0, 1, 0, 0), prodvers=(0, 1, 0, 0),
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
  ),
  kids=[
    StringFileInfo([StringTable('080404B0', [
      StringStruct('CompanyName', 'Modbus Studio'),
      StringStruct('FileDescription', 'Modbus Studio RTU 调试工具'),
      StringStruct('FileVersion', '0.2.0'),
      StringStruct('InternalName', 'ModbusStudio'),
      StringStruct('OriginalFilename', 'ModbusStudio.exe'),
      StringStruct('ProductName', 'Modbus Studio'),
      StringStruct('ProductVersion', '0.2.0')
    ])]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
""",
        encoding="utf-8",
    )
    return version_file


def _write_runtime_hook() -> Path:
    """Create an early Windows DLL loader for clean machines without VC runtime."""
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    hook = BUILD_DIR / "runtime_dll_paths.py"
    hook.write_text(
        """# Generated by build.py; executed before importing PySide6.
import ctypes
import os
from pathlib import Path
import sys

if sys.platform == "win32" and hasattr(sys, "_MEIPASS"):
    root = Path(sys._MEIPASS)
    pyside = root / "PySide6"
    for directory in (root, pyside, root / "shiboken6"):
        if directory.is_dir():
            os.add_dll_directory(str(directory))
            os.environ["PATH"] = str(directory) + os.pathsep + os.environ.get("PATH", "")
    # Load secondary dependencies explicitly. This avoids relying on a VC runtime
    # or ICU installation that happened to exist on the build computer.
    for candidate in (
        root / "icudt78.dll",
        root / "icuuc.dll",
        pyside / "VCRUNTIME140.dll",
        pyside / "VCRUNTIME140_1.dll",
        pyside / "MSVCP140.dll",
        pyside / "MSVCP140_1.dll",
        pyside / "MSVCP140_2.dll",
    ):
        if candidate.is_file():
            ctypes.WinDLL(str(candidate))
""",
        encoding="utf-8",
    )
    return hook


def _write_spec(png_path: Path, ico_path: Path, version_file: Path, runtime_hook: Path) -> Path:
    """Write a minimal PyInstaller spec that strips unused PySide6 plugins."""
    spec = BUILD_DIR / f"{APP_NAME}.spec"
    spec.write_text(
        f"""# -*- mode: python ; coding: utf-8 -*-

KEEP_PYSIDE_FILES = {{
    'qt6core.dll', 'qt6gui.dll', 'qt6widgets.dll',
    'qtcore.pyd', 'qtgui.pyd', 'qtwidgets.pyd', 'pyside6.abi3.dll',
}}
KEEP_PYSIDE_PLUGINS = {{
    'pyside6/plugins/platforms/qwindows.dll',
    'pyside6/plugins/imageformats/qico.dll',
    'pyside6/plugins/imageformats/qjpeg.dll',
}}
KEEP_TRANSLATIONS = {{
    'pyside6/translations/qt_zh_cn.qm',
    'pyside6/translations/qtbase_zh_cn.qm',
}}

def keep_pyside_entry(entry):
    name = entry[0].replace('\\\\', '/').lower()
    if not name.startswith('pyside6/'):
        return True
    base = name.rsplit('/', 1)[-1]
    if base in KEEP_PYSIDE_FILES:
        return True
    if base.startswith(('msvcp140', 'vcruntime140', 'concrt140')) and base.endswith('.dll'):
        return True
    return name in KEEP_PYSIDE_PLUGINS or name in KEEP_TRANSLATIONS

a = Analysis(
    [{str(ROOT / 'main.py')!r}],
    pathex=[{str(ROOT)!r}],
    binaries=[],
    datas=[({str(png_path)!r}, 'resources')],
    hiddenimports=['serial.tools.list_ports_windows'],
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[{str(runtime_hook)!r}],
    excludes={EXCLUDED_MODULES!r},
    noarchive=False,
    optimize=0,
)
a.binaries = [entry for entry in a.binaries if keep_pyside_entry(entry)]
a.datas = [entry for entry in a.datas if keep_pyside_entry(entry)]
pyz = PYZ(a.pure)
exe = EXE(
    pyz, a.scripts, a.binaries, a.datas, [],
    name={APP_NAME!r},
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    console=False,
    disable_windowed_traceback=False,
    version={str(version_file)!r},
    icon=[{str(ico_path)!r}],
)
""",
        encoding="utf-8",
    )
    return spec


def build(clean_artifacts: bool = False) -> Path:
    if os.name != "nt":
        raise SystemExit("此脚本用于生成 Windows EXE，请在 Windows 上运行。")
    _require_build_dependencies()

    from icon import generate

    png_path, ico_path = generate(RESOURCE_DIR)
    if clean_artifacts:
        for target in (BUILD_DIR, DIST_DIR):
            resolved = target.resolve()
            if resolved.parent != ROOT.resolve():
                raise RuntimeError(f"拒绝清理工作区之外的目录：{resolved}")
            if target.exists():
                shutil.rmtree(target)
        # The build directory was intentionally removed, recreate generated metadata.
        png_path, ico_path = generate(RESOURCE_DIR)

    version_file = _write_version_file()
    runtime_hook = _write_runtime_hook()
    spec_file = _write_spec(png_path, ico_path, version_file, runtime_hook)
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--distpath",
        str(DIST_DIR),
        "--workpath",
        str(BUILD_DIR / "pyinstaller"),
        str(spec_file),
    ]
    print("正在构建单文件 EXE，这通常需要一到几分钟……", flush=True)
    # Avoid accidentally collecting DLLs from unrelated programs on PATH (for
    # example Poppler's private ICU build). PyInstaller and Qt receive only the
    # Python and Windows runtime locations needed for this build.
    windows_dir = Path(os.environ.get("WINDIR", r"C:\Windows"))
    python_dir = Path(sys.executable).resolve().parent
    build_environment = dict(os.environ)
    build_environment["PATH"] = os.pathsep.join(
        str(path) for path in (python_dir, python_dir / "Scripts", windows_dir / "System32", windows_dir)
    )
    for variable in ("QT_PLUGIN_PATH", "QML2_IMPORT_PATH", "PYTHONPATH"):
        build_environment.pop(variable, None)
    subprocess.run(command, cwd=ROOT, env=build_environment, check=True)

    executable = DIST_DIR / f"{APP_NAME}.exe"
    if not executable.is_file() or executable.stat().st_size < 1_000_000:
        raise RuntimeError(f"打包结果无效：{executable}")
    size_mb = executable.stat().st_size / 1024 / 1024
    print(f"\n构建完成：{executable}")
    print(f"文件大小：{size_mb:.1f} MiB")
    print("该 EXE 为单文件版本，可复制到其他 64 位 Windows 电脑直接运行。")
    return executable


def main() -> int:
    parser = argparse.ArgumentParser(description="将 Modbus Studio 打包为单文件 Windows EXE")
    parser.add_argument(
        "--clean",
        action="store_true",
        help="打包前删除本项目的 build 和 dist 目录",
    )
    args = parser.parse_args()
    try:
        build(clean_artifacts=args.clean)
    except subprocess.CalledProcessError as exc:
        print(f"打包失败，PyInstaller 返回代码 {exc.returncode}", file=sys.stderr)
        return exc.returncode or 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
